from functools import wraps
from time import perf_counter
from typing import Callable, TypeVar


# ==========================================================
# [1] 데코레이터에서 사용할 타입 변수
# ==========================================================
# TypeVar는
# "원래 함수가 어떤 값을 반환하든
#  그 반환 타입을 그대로 유지한다"
# 라는 의미로 사용함
# ==========================================================

T = TypeVar("T")


# ==========================================================
# [2] 함수 실행 시간 측정 데코레이터
# ==========================================================
# 역할:
# - 함수 실행 직전 시간을 기록
# - 함수 실행
# - 함수 실행 직후 시간을 기록
# - 두 시간의 차이를 계산해 출력
#
# 사용 예:
#
# @measure_time
# def test():
#     ...
#
# 이렇게 하면 test()를 호출할 때
# 실행 시간이 자동 측정됨
# ==========================================================

def measure_time(
    func: Callable[..., T]
) -> Callable[..., T]:

    # ------------------------------------------------------
    # wraps(func)
    # ------------------------------------------------------
    # 데코레이터를 씌운 뒤에도
    # 원래 함수의 이름과 설명 등의 정보를 유지함
    # ------------------------------------------------------

    @wraps(func)
    def wrapper(
        *args,
        **kwargs,
    ) -> T:

        # 함수 시작 직전 시간
        start_time = perf_counter()

        # 원래 함수 실행
        result = func(
            *args,
            **kwargs,
        )

        # 함수 종료 직후 시간
        end_time = perf_counter()

        # 걸린 시간 계산
        elapsed_time = (
            end_time - start_time
        )

        print(
            f"[실행 시간] "
            f"{func.__name__}: "
            f"{elapsed_time:.6f}초"
        )

        # 원래 함수의 결과는 그대로 반환
        return result

    return wrapper