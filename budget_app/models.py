from dataclasses import dataclass, field


# ==========================================================
# [1] 거래 데이터 모델
# ==========================================================
# 역할:
# - 거래 한 건(Transaction)이 어떤 데이터를 가져야 하는지 정의함
# - 모든 거래가 같은 구조를 가지도록 기준을 만듦
# - repository.py, service.py 등 다른 파일에서 공통으로 사용함
# ==========================================================

@dataclass
class Transaction:

    # ======================================================
    # [1-1] 거래 기본 정보
    # ======================================================
    # id:
    # - 거래를 구분하기 위한 고유 번호
    #
    # type:
    # - 거래 종류
    # - income(수입) 또는 expense(지출)
    #
    # date:
    # - 거래 날짜
    # - 예: 2026-09-11
    #
    # amount:
    # - 거래 금액
    # - 정수(int)로 저장
    #
    # category:
    # - 거래 분류
    # - 예: food, transport, salary
    # ======================================================

    id: str
    type: str
    date: str
    amount: int
    category: str


    # ======================================================
    # [1-2] 선택 입력 정보
    # ======================================================
    # memo:
    # - 거래에 대한 간단한 메모
    # - 입력하지 않으면 빈 문자열("") 사용
    #
    # tags:
    # - 거래에 여러 개의 태그를 붙일 때 사용
    # - 문자열 목록(list[str]) 형태
    # - 입력하지 않으면 빈 리스트([])를 새로 생성
    # ======================================================

    memo: str = ""
    tags: list[str] = field(default_factory=list)